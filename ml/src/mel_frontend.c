static arm_rfft_fast_instance_f32 rfft_inst; /* init once, reuse across all 49 frames */
static float frame[1024];
static float spectrum[1024];
static float mag[513];
static float mel[40];
static float log_mel[40];
static float mfcc[10];
const float sqrt_scale = sqrtf(2.0 / 40.0);

void mel_frontend_init(void)
{
    arm_status status = arm_rfft_fast_init_f32(&rfft_inst, 1024);
    ASSERT(status == ARM_MATH_SUCCESS);
}

static int16_t ring_sample(const int16_t *ring, uint32_t start_idx, uint32_t offset)
{
    return ring[(start_idx + offset) % 16000u];
}

void mel_frontend_process(const int16_t *pcm_ring, uint32_t start_idx, float out_mfcc[49][10])
{

    // frame
    for (int i = 0; i < 49; i++)
    {

        __disable_irq();
        // normalize, window and pad
        for (int j = 0; j < 640; j++)
        {
            frame[j] =
                (ring_sample(pcm_ring, start_idx, i * 320 + j) / 32768.0f) * HANN_WINDOW_TABLE[j];
        }
        __enable_irq();
        for (int j = 640; j < 1024; j++)
        {
            frame[j] = 0.0f;
        }

        // FFT

        arm_rfft_fast_f32(&rfft_inst, frame, spectrum, 0);

        mag[0]   = fabsf(spectrum[0]);
        mag[512] = fabsf(spectrum[1]);

        // compute magnitude per bin
        for (int k = 1; k < 512; k++)
        {
            float re = spectrum[2 * k];
            float im = spectrum[2 * k + 1];
            mag[k]   = sqrtf(re * re + im * im);
        }

        // mel filterbank
        for (int m = 0; m < 40; m++)
        {
            float sum = 0;
            for (int k = 0; k < 513; k++)
            {
                sum += mag[k] * MEL_WEIGHT_MATRIX[k][m];
            }
            mel[m] = sum;
        }

        // log
        for (int m = 0; m < 40; m++)
        {
            log_mel[m] = logf(mel[m] + 1e-6f);
        }

        // DCT
        for (int n = 0; n < 10; n++)
        {
            float sum = 0;
            for (int m = 0; m < 40; m++)
            {
                sum += log_mel[m] * COS_TABLE[n][m];
            }
            mfcc[n] = sqrt_scale * sum;
        }

        // write to output array
        memcpy(out_mfcc[i], mfcc, 10 * sizeof(float));
    }
}

void mel_frontend_quantize(const float mfcc[49][10], int8_t out[490])
{
    for (int i = 0; i < 49; i++)
    {
        for (int j = 0; j < 10; j++)
        {
            float q = roundf(mfcc[i][j] / STAI_NETWORK_IN_1_SCALE) + STAI_NETWORK_IN_1_ZERO_POINT;
            if (q < -128)
                q = -128;
            if (q > 127)
                q = 127;
            out[i * 10 + j] = (int8_t)q;
        }
    }
}
