interpreter = tf.lite.Interpreter(model_content=tflite_model)
interpreter.allocate_tensors()
input_details = interpreter.get_input_details()[0]
output_details = interpreter.get_output_details()[0]
input_scale, input_zero_point = input_details["quantization"]

correct = 0
total = 0

for mfcc_batch, label_batch in test_ds:
    for mfcc, label in zip(mfcc_batch, label_batch):
        quantized_input = tf.round(mfcc / input_scale + input_zero_point)
        quantized_input = tf.clip_by_value(quantized_input, -128, 127)
        quantized_input = tf.cast(quantized_input, input_details["dtype"])
        quantized_input = tf.expand_dims(quantized_input, 0)  # add batch dim -> (1,49,10,1)

        interpreter.set_tensor(input_details["index"], quantized_input)
        interpreter.invoke()
        output = interpreter.get_tensor(output_details["index"])[0]

        predicted_label = tf.argmax(output).numpy()
        correct += int(predicted_label == label.numpy())
        total += 1

quantized_accuracy = correct / total
print(f"Quantized model test accuracy: {quantized_accuracy:.4f}")
