def build_calibration_dataset(entries, silence_waveforms, label_to_id, num_samples=300):
    paths = [p for p, _ in entries]
    label_ids = [label_to_id[l] for _, l in entries]
    word_ds = tf.data.Dataset.from_tensor_slices((paths, label_ids)).map(
        waveform_from_path, num_parallel_calls=tf.data.AUTOTUNE
    )

    silence_ids = tf.fill([len(silence_waveforms)], label_to_id["silence"])
    silence_ds = tf.data.Dataset.from_tensor_slices((tf.stack(silence_waveforms), silence_ids))

    ds = word_ds.concatenate(silence_ds)
    return ds.shuffle(2000, seed=42).take(num_samples)

def representative_dataset():
    calibration_ds = build_calibration_dataset(val_entries, val_silence, label_to_id, num_samples=300)

    for waveform, _ in calibration_ds:
        mfcc = extract_mfcc(waveform)
        mfcc = tf.expand_dims(mfcc, -1)  # add channel dim -> (49, 10, 1)
        mfcc = tf.expand_dims(mfcc, 0)   # add batch dim  -> (1, 49, 10, 1)
        yield [mfcc]

converter = tf.lite.TFLiteConverter.from_keras_model(model)
converter.optimizations = [tf.lite.Optimize.DEFAULT]
converter.representative_dataset = representative_dataset
converter.target_spec.supported_ops = [tf.lite.OpsSet.TFLITE_BUILTINS_INT8]
converter.inference_input_type = tf.int8
converter.inference_output_type = tf.int8
tflite_model = converter.convert()

with open("ds_cnn_s.tflite", "wb") as f:
    f.write(tflite_model)

test_loss, test_acc = model.evaluate(test_ds)
