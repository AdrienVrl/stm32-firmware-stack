def extract_mfcc(waveform):  # waveform: 16000 float32 samples in [-1, 1]
    stft = tf.signal.stft(
        waveform,
        frame_length=640,   # 40ms * 16kHz
        frame_step=320,     # 20ms * 16kHz
        fft_length=1024,
    )
    spectrogram = tf.abs(stft)

    mel_weight_matrix = tf.signal.linear_to_mel_weight_matrix(
        num_mel_bins=40,           # ARM's recipe computes 40 mel bins, then DCTs down to 10
        num_spectrogram_bins=stft.shape[-1],
        sample_rate=16000,
        lower_edge_hertz=20.0,
        upper_edge_hertz=4000.0,
    )
    mel_spectrogram = tf.matmul(spectrogram, mel_weight_matrix)
    log_mel = tf.math.log(mel_spectrogram + 1e-6)

    mfcc = tf.signal.mfccs_from_log_mel_spectrograms(log_mel)
    return mfcc[..., :10]   # keep first 10 cepstral coefficients

DATA_DIR = pathlib.Path("data/speech_commands_v0.02")
TARGET_WORDS = ["yes", "no", "up", "down", "left", "right", "on", "off", "stop", "go"]

def load_split_sets():
    val_set = set((DATA_DIR / "validation_list.txt").read_text().splitlines())
    test_set = set((DATA_DIR / "testing_list.txt").read_text().splitlines())
    return val_set, test_set

def gather_word_files():
    val_set, test_set = load_split_sets()
    splits = {"train": [], "val": [], "test": []}
    for word_dir in sorted(DATA_DIR.iterdir()):
        word = word_dir.name
        if not word_dir.is_dir() or word == "_background_noise_":
            continue
        label = word if word in TARGET_WORDS else "unknown"
        for wav_path in word_dir.glob("*.wav"):
            rel = f"{word}/{wav_path.name}"
            entry = (str(wav_path), label)
            bucket = "val" if rel in val_set else "test" if rel in test_set else "train"
            splits[bucket].append(entry)
    return splits

def time_shift(waveform, max_shift_samples=1600):
    length = tf.shape(waveform)[0]
    shift = tf.random.uniform([], -max_shift_samples, max_shift_samples + 1, dtype=tf.int32)

    pad_start = tf.maximum(shift, 0)
    pad_end = tf.maximum(-shift, 0)
    padded = tf.pad(waveform, [[pad_start, pad_end]])

    offset = tf.maximum(-shift, 0)
    return padded[offset:offset + length]

def mix_in_background_noise(waveform, noise_pool, background_frequency=0.8, max_background_volume=0.1):
    apply_noise = tf.cast(tf.random.uniform([]) < background_frequency, tf.float32)
    volume = tf.random.uniform([], 0.0, max_background_volume) * apply_noise

    idx = tf.random.uniform([], 0, tf.shape(noise_pool)[0], dtype=tf.int32)
    noise_segment = noise_pool[idx]

    mixed = waveform + volume * noise_segment
    return tf.clip_by_value(mixed, -1.0, 1.0)


def build_noise_segment_pool(background_clips, num_segments=200, segment_len=16000):
    pool = []
    for _ in range(num_segments):
        clip = background_clips[random.randrange(len(background_clips))]
        start = random.randrange(0, len(clip) - segment_len)
        pool.append(clip[start:start + segment_len])
    return tf.constant(np.stack(pool), dtype=tf.float32)  # shape (num_segments, 16000)

def balance_unknown(entries, target_count_per_split):
    words = [e for e in entries if e[1] != "unknown"]
    unknown = [e for e in entries if e[1] == "unknown"]
    random.shuffle(unknown)
    return words + unknown[:target_count_per_split]

def load_background_clips():
    bg_dir = DATA_DIR / "_background_noise_"
    clips = []
    for wav_path in bg_dir.glob("*.wav"):
        audio = tf.audio.decode_wav(tf.io.read_file(str(wav_path)), desired_channels=1).audio
        clips.append(tf.squeeze(audio, axis=-1).numpy())  # 1D float32 array
    return clips

def make_silence_waveforms(clips, count):
    out = []
    for _ in range(count):
        clip = clips[random.randrange(len(clips))]
        start = random.randrange(0, len(clip) - 16000)
        out.append(clip[start:start + 16000])
    return out

def waveform_from_path(path, label_id):
    audio = tf.audio.decode_wav(tf.io.read_file(path), desired_channels=1, desired_samples=16000).audio
    return tf.squeeze(audio, axis=-1), label_id

def augment_waveform(waveform, label_id, noise_pool):
    waveform = time_shift(waveform)
    waveform = mix_in_background_noise(waveform, noise_pool)
    return waveform, label_id

def build_dataset(word_entries, silence_waveforms, label_to_id, training):
    paths = [p for p, _ in word_entries]
    label_ids = [label_to_id[l] for _, l in word_entries]
    word_ds = tf.data.Dataset.from_tensor_slices((paths, label_ids)).map(
        waveform_from_path, num_parallel_calls=tf.data.AUTOTUNE
    )

    silence_ids = tf.fill([len(silence_waveforms)], label_to_id["silence"])
    silence_ds = tf.data.Dataset.from_tensor_slices(
        (tf.stack(silence_waveforms), silence_ids)
    )

    ds = word_ds.concatenate(silence_ds)
    noise_pool = build_noise_segment_pool(bg_clips)
    if training:
        ds = ds.map(lambda wav, lbl: augment_waveform(wav, lbl, noise_pool),
                  num_parallel_calls=tf.data.AUTOTUNE)
        ds = ds.shuffle(4096)

    ds = ds.map(
        lambda wav, lbl: (extract_mfcc(wav), lbl),
        num_parallel_calls=tf.data.AUTOTUNE,
    )
    ds = ds.map(lambda mfcc, lbl: (tf.expand_dims(mfcc, -1), lbl))  # add channel dim -> (49,10,1)
    return ds.batch(100).prefetch(tf.data.AUTOTUNE)

